class VectorDBManager:
    def __init__(self, persist_directory: str = "./chroma_db"):
        # Remove any existing persistent directory to force a fresh initialization.
        if os.path.exists(persist_directory):
            shutil.rmtree(persist_directory)
            print(f"Deleted existing database at {persist_directory}.")
        else:
            print("No existing database directory found.")

        # Create settings for the Chromadb client with the persistent directory.
        settings = Settings(persist_directory=persist_directory)
        self.client = chromadb.Client(settings=settings)

        # Initialize the embedding function.
        self.embed_model = embedding_functions.SentenceTransformerEmbeddingFunction("all-mpnet-base-v2")
        collection_name = "literature_review"

        # Use get_or_create to either create a new collection or retrieve the existing one.
        self.collection = self.client.create_collection(
            name=collection_name,
            embedding_function=self.embed_model,
            metadata={"hnsw:space": "cosine"},
            get_or_create=True
        )
        print("VectorDBManager initialized successfully with a fresh database.")

    def store_articles(self, articles: List[dict]):
        """Store articles with enhanced academic metadata."""
        ids, documents, metadatas = [], [], []
        for article in articles:
            for chunk in article["chunks"]:
                ids.append(f"{article['id']}_{chunk['citation_key']}")
                documents.append(chunk["text"])
                # Proper author handling
                authors = article.get("authors", "Unknown")
                if isinstance(authors, list):
                    authors_str = ", ".join(authors)
                else:
                    authors_str = str(authors)
                metadatas.append({
                    "title": article["title"],
                    "authors": authors_str,
                    "year": article["year"],
                    "section": chunk["section"],
                    "citation_key": chunk["citation_key"],
                    "source": "arxiv",
                    "pdf_url": article.get("pdf_url", "No PDF URL")
                })
        self.collection.upsert(
            documents=documents,
            metadatas=metadatas,
            ids=[f"{article['id']}_chunk{idx}_{uuid.uuid4()}" for idx in range(len(documents))]
        )
        print("Articles stored successfully.")

