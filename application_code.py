def main_pipeline_end_to_end_sync(query: str, research_objective: str, start_year: int, min_citations: int, limit: int = 30) -> dict:
    logging.info("=== Starting End-to-End Pipeline ===")

    # 1. Review Question Formulation
    rqf = ReviewQuestionFormulator()
    keywords_list = rqf.extract_keywords(research_objective)
    print("Extracted Keywords from Research Objective:")
    print(keywords_list)

    review_questions_with_pcc = rqf.generate_review_questions_with_pcc(query)
    print("\nGenerated Review Questions with PCC Elements:")
    print(json.dumps(review_questions_with_pcc, indent=2))

    # Create an instance of the TIM Pathway Mapper
    tim_mapper = TIMPathwayMapper()

# For each generated review question, map the PCC elements to a pathway and print the result
    for idx, question in enumerate(review_questions_with_pcc):
        mapped_pathway = tim_mapper.map_to_pathway(question["pcc"])
        print(f"\nQuestion {idx+1}: {question['question']}")
        print("PCC Elements:", question["pcc"])
        print("Mapped Pathway:", mapped_pathway)

    # 2. Paper Retrieval
    pcc_elements = {"population": "", "concept": "", "context": ""}
    tim_mapper = TIMPathwayMapper()
    retriever = PaperRetriever(api_key="", tim_mapper=tim_mapper)
    questions_with_pcc = [{"question": query, "pcc": pcc_elements}]
    articles = retriever.unified_retrieval(questions_with_pcc, max_results=limit)
    print("\nNumber of articles retrieved:", len(articles))
    if articles:
        print("Sample Retrieved Article:")
        print(json.dumps(articles[0], indent=2))

    # 3. Screening and Duplicate Removal
    screening = ArticleScreening()
    screened_articles, exclusion_details = screening.screen_articles(articles, start_year=start_year, relevance_keywords=keywords_list)
    print("\nNumber of articles after screening:", len(screened_articles))

    deduped_articles = screening.remove_duplicates(screened_articles)
    duplicates_removed = len(screened_articles) - len(deduped_articles)
    print("Number of articles after deduplication:", len(deduped_articles))

    # 4. Compute Semantic Similarity Scores
    semantic_sim = SemanticSimilarity(model_name='all-mpnet-base-v2')
    deduped_articles = semantic_sim.add_similarity_scores(deduped_articles, research_objective)
    print("\nSemantic similarity scores computed for deduplicated articles.")

    # 5. Quality Assessment and PRISMA Summary Generation
    prisma_summary = PrismaSummary(quality_threshold=0.5)
    quality_assessed_articles = prisma_summary.assess_quality(deduped_articles)
    qa_excluded = len(deduped_articles) - len(quality_assessed_articles)
    quality_assessed_count = len(quality_assessed_articles)
    included = quality_assessed_count
    print("\nNumber of articles after quality assessment:", quality_assessed_count)
    print("Number of articles excluded during QA:", qa_excluded)

    retrieved_count = len(articles)
    screened_count = len(screened_articles)
    prisma_text_summary = prisma_summary.generate_text_summary(
        retrieved=retrieved_count,
        screened=screened_count,
        duplicates_removed=duplicates_removed,
        quality_assessed=quality_assessed_count,
        included=included,
        screening_details=exclusion_details,
        qa_excluded=qa_excluded
    )
    print("\n--- PRISMA Text Summary ---\n")
    print(prisma_text_summary)

    sankey_fig = prisma_summary.create_interactive_visualization(
        retrieved=retrieved_count,
        screened=screened_count,
        duplicates_removed=duplicates_removed,
        quality_assessed=quality_assessed_count,
        included=included,
        screening_details=exclusion_details
    )
    # Export PRISMA outputs
    with open("prisma_report.txt", "w") as f:
        f.write(prisma_text_summary)
    sankey_fig.write_html("prisma_sankey.html")
    prisma_summary.export_to_rayyan_csv(quality_assessed_articles)

    # 7. Data Extraction and Vector DB Storage
    vector_db = VectorDBManager(persist_directory="./chroma_db")
    pdf_downloader = PDFDownloader()
    data_extractor = DataExtractor(openai_client=openai, vector_db=vector_db, pdf_downloader=pdf_downloader)
    extracted_data = data_extractor.process_articles(deduped_articles)
    print("\n=== Data Extraction Test ===")
    print("Number of articles processed:", len(extracted_data))
    if extracted_data:
        sample_article = extracted_data[0]
        print("Sample Enriched Article:")
        print("Title:", sample_article.get("title"))
        print("Extracted Keywords:", sample_article.get("keywords"))
        print("Number of chunks:", len(sample_article.get("chunks", [])))

    # 8. Methodology Extraction and Analysis (Synchronous)
    methodology_frequency = analyze_methodologies_sync(extracted_data, max_workers=5)
    print("\n=== Methodology Extraction Test ===")
    print("Methodology frequency:", methodology_frequency)
    methodology_insights = get_methodology_insights_sync(methodology_frequency, research_objective, client)
    print("\nMethodology Insights:")
    print(json.dumps(methodology_insights, indent=2))
    # Generate the Plotly figure
    methodology_fig = plot_top_five_methodologies(methodology_frequency)

    # 9. Analysis and Synthesis
    analysis_result = analysis_synthesis_tool(json.dumps(extracted_data, indent=2))
    synthesized_narrative = analysis_result.get("structured_response", "No output produced.")
    print("\n=== Analysis and Synthesis Test ===")
    print("Synthesized Narrative:\n", synthesized_narrative)

    # 10. Interpretation
    interpreted_summary = run_interpretation_sync(synthesized_narrative)
    print("\n=== Interpretation Test ===")
    print("Interpreted Summary:\n", interpreted_summary)

    # 11. Literature Review Writing
    inputs = {
        "synthesized_narrative": synthesized_narrative,
        "interpreted_summary": interpreted_summary,
        "prisma_summary": prisma_text_summary
    }
    final_review = run_literature_review_writing_sync(inputs, json.dumps(methodology_insights, indent=2))
    print("\n=== Literature Review Writing Test ===")
    print("Final Literature Review Draft:\n", final_review)

    # --- Step 12: Evaluation of RAG Output ---

# Use the final literature review draft as the generated output.
# For retrieved documents, we extract (for example) the abstracts from the quality-assessed articles.
    retrieved_docs_texts = [article.get("abstract", "") for article in quality_assessed_articles]

# Initialize the EvaluationDriver (assumes the evaluators have been defined in previous cells).
    eval_driver = EvaluationDriver()

# Evaluate the final review against the original query using the actual retrieved documents.
    evaluation_results = eval_driver.evaluate(query, final_review, retrieved_docs_texts)

    print("\n=== Evaluation Driver Results ===")
    print(f"Relevance Score: {evaluation_results['relevance_score']:.2f}")
    print(f"Groundedness Score: {evaluation_results['groundedness_score']:.2f}")
    print(f"Retrieval Relevance Score: {evaluation_results['retrieval_relevance_score']:.2f}")

    # Log the current run's evaluation metrics to the CSV file.
    log_evaluation_results(query, final_review, evaluation_results)

    # 13. LLM Judge for Quality Control
    judge_feedback = llm_judge_sync(final_review)
    print("LLM Judge Feedback:\n", judge_feedback)
    log_judge_feedback_sync(final_review, judge_feedback)

    # 14. Additional Visualizations from VisualizationModule
    vis_module = VisualizationModule(deduped_articles)
    if not vis_module.papers:
        print("No articles available for additional visualization.")
        bar_chart = px.bar(title="No Data to Display")
