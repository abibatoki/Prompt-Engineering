"""#📌 Analysis and Synthesis Module"""

def split_text_by_tokens(text: str, max_tokens: int) -> list:
    """
    Split the input text into chunks, each with at most max_tokens tokens,
    using the tiktoken encoding for GPT-3.5-turbo.
    """
    # Use the encoding for GPT-3.5-turbo; "cl100k_base" is recommended.
    encoding = tiktoken.get_encoding("cl100k_base")
    token_ids = encoding.encode(text)
    chunks = []
    for i in range(0, len(token_ids), max_tokens):
        chunk_ids = token_ids[i:i+max_tokens]
        chunk_text = encoding.decode(chunk_ids)
        chunks.append(chunk_text)
    return chunks

def analysis_synthesis_tool(input_text: str, max_tokens: int = 1500) -> dict:
    """
    Analyzes and synthesizes the input text by splitting it into tokenized chunks
    to avoid exceeding the model's context length.

    Parameters:
        input_text (str): The full text to be analyzed.
        max_tokens (int): The maximum number of tokens per chunk.

    Returns:
        dict: A dictionary with the synthesized narrative under 'structured_response'.
    """
    llm = ChatOpenAI(model_name="gpt-3.5-turbo", temperature=0)

    # Split the input text into token-accurate chunks.
    chunks = split_text_by_tokens(input_text, max_tokens)

    synthesized_chunks = []
    prompt_template = (
        """You are an expert academic researcher. You have been provided with extracted data, including summaries, methods, results, conclusions, and metadata such as authors and publication details:

{chunk}

Please analyze and synthesize this data into a clear academic narrative that addresses the research question. Your narrative should include:
1. A summary of the main findings and trends.
2. Identification of key research themes.
3. Discussion of the framework and/or research methods employed over time in this research area.
4. A concluding synthesis of implication of findings.
5. Inline citations (e.g., Author, Year) throughout the narrative to trace factual sources.

Ensure your response is well-structured and coherent, with logical flow and clarity."""
    )

    for chunk in chunks:
        prompt = prompt_template.format(chunk=chunk)
        response = llm.invoke([{"role": "user", "content": prompt}])
        synthesized_chunks.append(response.content.strip())

    # Combine all chunk outputs into one synthesized narrative.
    synthesized = " ".join(synthesized_chunks)
    return {"structured_response": synthesized}

