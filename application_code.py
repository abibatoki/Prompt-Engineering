def log_evaluation_results(query: str, final_review: str, evaluation_results: dict, log_file: str = "evaluation_log.csv"):
    """
    Logs the evaluation results along with the query and a brief excerpt from the final review into a CSV file.

    Parameters:
      - query: The input query used for the pipeline run.
      - final_review: The generated final literature review.
      - evaluation_results: A dictionary containing the scores from the evaluation driver.
      - log_file: The CSV file to which results are appended.
    """
    # Define the fields to log.
    fieldnames = [
        "timestamp",
        "query",
        "relevance_score",
        "groundedness_score",
        "retrieval_relevance_score",
        "final_review_excerpt"
    ]

    timestamp = datetime.datetime.now().isoformat()
    # Extract a brief excerpt from the final review (first 100 characters).
    review_excerpt = final_review[:100]

    # Check if the log file already exists.
    file_exists = os.path.exists(log_file)

    # Open the log file in append mode.
    with open(log_file, "a", newline="", encoding="utf-8") as csvfile:
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        # If the file is new, write the header.
        if not file_exists:
            writer.writeheader()
        # Write the evaluation record.
        writer.writerow({
            "timestamp": timestamp,
            "query": query,
            "relevance_score": evaluation_results.get("relevance_score", 0),
            "groundedness_score": evaluation_results.get("groundedness_score", 0),
            "retrieval_relevance_score": evaluation_results.get("retrieval_relevance_score", 0),
            "final_review_excerpt": review_excerpt
        })
    print(f"Evaluation results logged to {log_file}")

def aggregate_evaluation_logs(log_file: str = "evaluation_log.csv"):
    """
    Aggregates evaluation scores from the CSV log file and prints the average scores.

    Parameters:
      - log_file: The CSV file containing logged evaluation records.
    """
    if not os.path.exists(log_file):
        print("No evaluation logs found.")
        return

    relevance_scores = []
    groundedness_scores = []
    retrieval_relevance_scores = []

    with open(log_file, "r", newline="", encoding="utf-8") as csvfile:
        reader = csv.DictReader(csvfile)
        for row in reader:
            try:
                relevance_scores.append(float(row["relevance_score"]))
                groundedness_scores.append(float(row["groundedness_score"]))
                retrieval_relevance_scores.append(float(row["retrieval_relevance_score"]))
            except Exception as e:
                print("Error parsing row:", row, e)

    avg_relevance = sum(relevance_scores) / len(relevance_scores) if relevance_scores else 0
    avg_groundedness = sum(groundedness_scores) / len(groundedness_scores) if groundedness_scores else 0
    avg_retrieval_relevance = sum(retrieval_relevance_scores) / len(retrieval_relevance_scores) if retrieval_relevance_scores else 0

    print("\n=== Aggregated Evaluation Metrics ===")
    print(f"Average Relevance Score: {avg_relevance:.2f}")
    print(f"Average Groundedness Score: {avg_groundedness:.2f}")
    print(f"Average Retrieval Relevance Score: {avg_retrieval_relevance:.2f}")

