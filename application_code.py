"""#📌 Article Retrieval Module"""

class RateLimiter:
    def __init__(self, requests_per_minute: int = 100):
        self.requests_per_minute = requests_per_minute
        self.last_request_time = 0

    def wait_if_needed(self) -> None:
        current_time = time.time()
        elapsed = current_time - self.last_request_time
        wait_time = max(0, (60 / self.requests_per_minute) - elapsed)
        if wait_time > 0:
            time.sleep(wait_time)
        self.last_request_time = time.time()

class PaperRetriever:
    def __init__(self, api_key: str, tim_mapper: 'TIMPathwayMapper'):
        self.tim_mapper = tim_mapper
        self.rate_limiter = RateLimiter(requests_per_minute=60)
        self.max_retries = 3
        self.retry_delay = 5

    def contextualize_query(self, base_query: str, pcc_elements: Dict[str, str]) -> str:
        pathway = self.tim_mapper.map_to_pathway(pcc_elements)
        logging.info(f"Mapped query to pathway: {pathway}")
        if pathway in self.tim_mapper.PATHWAY_PROFILES:
            profile = self.tim_mapper.PATHWAY_PROFILES[pathway]
            context_keywords = " ".join(profile["concepts"])
            final_query = f"{base_query} {context_keywords} {profile['context']}"
        else:
            final_query = base_query
        logging.info(f"Final query used for retrieval: {final_query}")
        return final_query

    def fetch_from_arxiv(self, query: str, limit: int = 10) -> List[Dict[str, Union[str, int]]]:
        """
        Queries the arXiv API using the provided query and returns a list of paper dictionaries.
        Each paper dictionary includes fields such as title, abstract, published_date, citation_count,
        link, source, authors, and id.
        """
        base_url = "http://export.arxiv.org/api/query"
        params = {
            "search_query": query,
            "start": 0,
            "max_results": limit
        }
        for attempt in range(self.max_retries):
            try:
                self.rate_limiter.wait_if_needed()
                response = requests.get(base_url, params=params, timeout=30)
                response.raise_for_status()
                break
            except requests.exceptions.RequestException as e:
                if attempt < self.max_retries - 1:
                    time.sleep(self.retry_delay * (attempt + 1))
                else:
                    raise Exception(f"arXiv API request failed: {str(e)}")

        # Parse the XML response from arXiv.
        root = ET.fromstring(response.text)
        ns = {"atom": "http://www.w3.org/2005/Atom", "arxiv": "http://arxiv.org/schemas/atom"}
        papers = []
        for entry in root.findall("atom:entry", ns):
            title_elem = entry.find("atom:title", ns)
            abstract_elem = entry.find("atom:summary", ns)
            published_elem = entry.find("atom:published", ns)
            author_elems = entry.findall("atom:author", ns)
            authors = [author.find("atom:name", ns).text.strip() for author in author_elems if author.find("atom:name", ns) is not None]
            id_elem = entry.find("atom:id", ns)
            article_id = id_elem.text.strip() if id_elem is not None else (
                f"{title_elem.text.strip()}_{published_elem.text.strip()[:4]}"
                if (title_elem is not None and published_elem is not None) else "unknown_id"
            )
            link_elem = None
            for link in entry.findall("atom:link", ns):
                if link.attrib.get("rel") == "alternate":
                    link_elem = link
                    break
            title = title_elem.text.strip() if title_elem is not None else "No Title"
            abstract = abstract_elem.text.strip() if abstract_elem is not None else "No Abstract"
            published_date = published_elem.text.strip() if published_elem is not None else "Unknown"
            year = published_date.split("-")[0] if published_date != "Unknown" else "Unknown"

            # Remove references to download count. Set default citation_count to 0.
            citation_count = 0

            link = link_elem.attrib.get("href", "No Link Available") if link_elem is not None else "No Link Available"

            # Extract DOI if available (this assumes arXiv provides it under the "arxiv:doi" tag)
            doi_elem = entry.find("arxiv:doi", ns)
            doi = doi_elem.text.strip() if doi_elem is not None else None

            paper = {
                "id": article_id,
                "title": title,
                "abstract": abstract,
                "published_date": published_date,
                "year": year,
                "citation_count": citation_count,
                "link": link,
                "source": "arXiv",
                "authors": authors,
                "doi": doi  # Optionally store the DOI
            }
            papers.append(paper)
        return papers

    def unified_retrieval(self, questions_with_pcc: List[dict], max_results: int = 100) -> List[dict]:
        """
        Pathway-optimized retrieval that concurrently processes multiple queries.
        """
        all_papers = []
        queries = [
            self.contextualize_query(question["question"], question["pcc"])
            for question in questions_with_pcc
        ]
        # Using ThreadPoolExecutor to batch API calls concurrently
        with ThreadPoolExecutor(max_workers=len(queries)) as executor:
            future_to_query = {
                executor.submit(self.fetch_from_arxiv, query, max_results // len(queries)): query
                for query in queries
            }
            for future in as_completed(future_to_query):
                try:
                    papers = future.result()
                    all_papers.extend(papers)
                except Exception as e:
                    logging.error(f"Error fetching papers for query '{future_to_query[future]}': {e}")
        return all_papers

