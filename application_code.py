# semantic_similarity_module.py
class SemanticSimilarity:
    def __init__(self, model_name: str = 'all-mpnet-base-v2'):
        self.model = SentenceTransformer(model_name)

    def add_similarity_scores(self, articles: list, research_objective: str) -> list:
        """
        Adds a new 'semantic_similarity_score' key to each article dict,
        based on the cosine similarity between the article's abstract and the research objective.

        Parameters:
            articles (list): A list of article dictionaries. Each dict should have an 'abstract' key.
            research_objective (str): The research objective text to compare against.

        Returns:
            list: The same list of article dictionaries, but each now includes a
                  'semantic_similarity_score' key with a float value.
        """
        # Encode the research objective once
        research_emb = self.model.encode(research_objective, convert_to_tensor=True)

        # Compute similarity for each article
        for article in articles:
            abstract = article.get("abstract", "")
            if abstract:
                article_emb = self.model.encode(abstract, convert_to_tensor=True)
                sim = float(util.pytorch_cos_sim(article_emb, research_emb).item())
            else:
                sim = 0.0
            article["semantic_similarity_score"] = sim

        return articles

"""#📌 PDF Downloader"""

class PDFDownloader:
    def __init__(self):
        self.chunk_size = 1500
        self.section_headers = [
            "abstract", "introduction", "methods",
            "results", "discussion", "conclusion"
        ]

    def get_full_text(self, article: dict) -> str:
        """
        Download the PDF from the article's link and extract its full text.
        Only processes articles that passed quality assessment (semantic_similarity_score >= 0.5).
        If the PDF cannot be retrieved or processed, or if the article did not pass quality assessment,
        fall back to using the article's abstract.
        """
        # Only process if article has passed quality assessment.
        # If the article's semantic_similarity_score is below 0.5, return the abstract.
        if float(article.get("semantic_similarity_score", 0)) < 0.5:
            return article.get("abstract", "No Abstract Available")

        pdf_url = article.get("pdf_url", None)
        if not pdf_url:
            return article.get("abstract", "No Abstract Available")

        try:
            response = requests.get(pdf_url, timeout=30)
            response.raise_for_status()
            with open("temp.pdf", "wb") as f:
                f.write(response.content)
            doc = fitz.open("temp.pdf")
            full_text = ""
            for page in doc:
                full_text += page.get_text()
            doc.close()
            os.remove("temp.pdf")
            return full_text if full_text else article.get("abstract", "No Abstract Available")
        except Exception as e:
            logging.error(f"Error extracting PDF text: {str(e)}")
            return article.get("abstract", "No Abstract Available")

    def _extract_arxiv_metadata(self, entry) -> dict:
        """Parse arXiv XML metadata including authors"""
        return {
            "title": entry.find("atom:title", {"atom": ""}).text.strip(),
            "authors": [a.text for a in entry.findall("atom:author/atom:name", {"atom": ""})],
            "year": entry.find("atom:published", {"atom": ""}).text[:4],
            "link": entry.find("atom:link[@rel='alternate']", {"atom": ""}).attrib["href"]
        }

    def _chunk_and_categorize(self, text: str) -> List[dict]:
        """Section-aware chunking with citation anchors"""
        chunks = []
        current_section = "preface"
        buffer = []

        for line in text.split('\n'):
            detected_section = self._detect_section_header(line)
            if detected_section:
                if buffer:
                    chunks.append(self._create_chunk(buffer, current_section))
                current_section = detected_section
                buffer = []
            buffer.append(line)

            if len("\n".join(buffer)) > self.chunk_size:
                chunks.append(self._create_chunk(buffer, current_section))
                buffer = []

        if buffer:
            chunks.append(self._create_chunk(buffer, current_section))
        return chunks

    def _create_chunk(self, buffer: list, section: str) -> dict:
        return {
            "text": "\n".join(buffer),
            "section": section,
            "citation_key": f"{hash(''.join(buffer[:3])):x}"  # Unique content-based ID
        }

