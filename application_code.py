def count_tokens(text, model="gpt-4"):
    encoding = tiktoken.encoding_for_model(model)
    return len(encoding.encode(text))

def literature_review_writing_tool_sync(inputs: dict, methodology_insights: str) -> str:
    """
    Synchronously writes the literature review draft using chunking and error handling
    to avoid exceeding token limits.
    """
    # Construct the full prompt
    base_prompt = f"""You are an expert academic writer. Synthesize a concise and comprehensive literature review draft using the following inputs:
- **Synthesized Narrative**: {inputs['synthesized_narrative']}
- **Interpreted Summary**: {inputs['interpreted_summary']}
- **PRISMA Summary**: {inputs['prisma_summary']}
- **Methodology Insights**: {methodology_insights}

Ensure the review is well-structured, clearly written, and appropriately integrates these components into a cohesive narrative.
    """

    # Maximum tokens available for the prompt (reserve some for the completion)
    max_context_tokens = 8192 - 500  # adjust reserve as needed

    # If the prompt is too long, break it into smaller chunks.
    if count_tokens(base_prompt, model="gpt-4") > max_context_tokens:
        # Define an initial chunk size in characters (heuristic)
        chunk_size = 10000
        chunks = []
        for i in range(0, len(base_prompt), chunk_size):
            chunk = base_prompt[i:i + chunk_size]
            # Ensure the chunk is within the token limit by trimming if needed.
            while count_tokens(chunk, model="gpt-4") > max_context_tokens and len(chunk) > 0:
                chunk = chunk[:-100]  # trim off 100 characters and check again
            chunks.append(chunk)
    else:
        chunks = [base_prompt]

    response_text = ""
    for chunk in chunks:
        try:
            response = openai.chat.completions.create(
                model="gpt-4",
                messages=[{"role": "user", "content": chunk}],
                temperature=0.7,
                max_tokens=500  # reduce max_tokens to keep total within limits
            )
            response_text += response.choices[0].message.content.strip()
            # Short delay between chunks
            time.sleep(1)
        except RateLimitError as e:
            print(f"Rate limit error encountered: {e}. Waiting...")
            time.sleep(10)  # wait longer before retrying
        except BadRequestError as e:
            print(f"Invalid request error encountered: {e}. Likely due to exceeding context length. Consider further reducing input size.")
        except Exception as e:
            print(f"An unexpected error occurred: {e}")

    return response_text

def run_literature_review_writing_sync(inputs: dict, methodology_insights: str) -> str:
    """
    Synchronously runs the literature review writing tool.
    """
    return literature_review_writing_tool_sync(inputs, methodology_insights)

