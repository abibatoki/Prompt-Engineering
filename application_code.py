class RelevanceEvaluator:
    def __init__(self, model_name="all-mpnet-base-v2"):
        # Initialize the sentence transformer model
        self.model = SentenceTransformer(model_name)

    def evaluate(self, generated_output: str, query: str) -> float:
        """
        Evaluates the relevance of the generated output to the query using cosine similarity.

        Parameters:
            generated_output (str): The output produced by the RAG system.
            query (str): The user query or research objective.

        Returns:
            float: A similarity score between 0 and 1 representing relevance.
        """
        # Encode the query and the generated output into embeddings
        query_embedding = self.model.encode(query, convert_to_tensor=True)
        output_embedding = self.model.encode(generated_output, convert_to_tensor=True)

        # Calculate cosine similarity between the embeddings
        similarity = util.pytorch_cos_sim(query_embedding, output_embedding).item()
        return similarity

"""#📌 Groundedness Evaluator"""

# groundedness_evaluator.py

class GroundednessEvaluator:
    def __init__(self, model_name="all-mpnet-base-v2"):
        # Initialize the sentence transformer model
        self.model = SentenceTransformer(model_name)

    def evaluate(self, generated_output: str, retrieved_docs: list) -> float:
        """
        Evaluates the groundedness of the generated output based on the retrieved documents.

        Parameters:
            generated_output (str): The output produced by the RAG system.
            retrieved_docs (list of str): A list of documents (or excerpts) retrieved from the source.

        Returns:
            float: A groundedness score between 0 and 1.
        """
        if not retrieved_docs:
            # If there are no retrieved documents, we consider the output to have no grounding.
            return 0.0

        # Encode the generated output
        output_embedding = self.model.encode(generated_output, convert_to_tensor=True)

        # Compute similarity scores for each retrieved document
        similarities = []
        for doc in retrieved_docs:
            doc_embedding = self.model.encode(doc, convert_to_tensor=True)
            similarity = util.pytorch_cos_sim(output_embedding, doc_embedding).item()
            similarities.append(similarity)

        # Aggregate similarities. Here we use the average as a proxy measure.
        groundedness_score = sum(similarities) / len(similarities)
        return groundedness_score

"""#📌 Retrieval Relevance Evaluator"""

# retrieval_relevance_evaluator.py
class RetrievalRelevanceEvaluator:
    def __init__(self, model_name="all-mpnet-base-v2"):
        # Initialize the sentence transformer model
        self.model = SentenceTransformer(model_name)

    def evaluate(self, query: str, retrieved_docs: list) -> float:
        """
        Evaluates the relevance of the retrieved documents relative to the query.

        Parameters:
            query (str): The input query or research objective.
            retrieved_docs (list of str): A list of documents (or excerpts) retrieved by the system.

        Returns:
            float: A retrieval relevance score between 0 and 1.
        """
        if not retrieved_docs:
            # If no documents were retrieved, return a score of 0
            return 0.0

        # Encode the query
        query_embedding = self.model.encode(query, convert_to_tensor=True)

        # Compute cosine similarity between the query and each retrieved document
        similarities = []
        for doc in retrieved_docs:
            doc_embedding = self.model.encode(doc, convert_to_tensor=True)
            similarity = util.pytorch_cos_sim(query_embedding, doc_embedding).item()
            similarities.append(similarity)

        # Aggregate the similarities; here we take the average as the overall relevance score.
        relevance_score = sum(similarities) / len(similarities)
        return relevance_score

"""#📌 Evaluation Driver"""

# Evaluation Driver Code

class EvaluationDriver:
    def __init__(self):
        self.relevance_evaluator = RelevanceEvaluator()
        self.groundedness_evaluator = GroundednessEvaluator()
        self.retrieval_relevance_evaluator = RetrievalRelevanceEvaluator()

    def evaluate(self, query: str, generated_output: str, retrieved_docs: list) -> dict:
        relevance_score = self.relevance_evaluator.evaluate(generated_output, query)
        groundedness_score = self.groundedness_evaluator.evaluate(generated_output, retrieved_docs)
        retrieval_relevance_score = self.retrieval_relevance_evaluator.evaluate(query, retrieved_docs)

        return {
            "relevance_score": relevance_score,
            "groundedness_score": groundedness_score,
            "retrieval_relevance_score": retrieval_relevance_score
        }

