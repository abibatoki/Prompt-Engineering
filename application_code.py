class ArticleScreening:
    def __init__(self):
        self.model = SentenceTransformer('all-mpnet-base-v2')
        self.similarity_threshold = 0.85

    def screen_articles(self, papers, start_year=None, relevance_keywords=None):
        """
        Returns:
            screened_papers (list): The articles that pass screening.
            exclusion_details (dict): A dictionary counting how many were excluded for each reason.
        """
        screened_papers = []
        exclusion_details = {
            "Publication Year": 0,
            "Relevance": 0
        }

        for paper in papers:
            # Check publication year
            try:
                year = int(paper.get("year", "0"))
            except ValueError:
                year = 0

            # Reason 1: Publication Year
            if start_year and year < start_year:
                exclusion_details["Publication Year"] += 1
                continue  # skip adding to screened_papers

            # Reason 2: Relevance
            if relevance_keywords:
                text = (paper.get("title", "") + " " + paper.get("abstract", "")).lower()
                if not any(kw.lower() in text for kw in relevance_keywords):
                    exclusion_details["Relevance"] += 1
                    continue

            # If it wasn't excluded for any reason, it passes screening
            screened_papers.append(paper)

        return screened_papers, exclusion_details

    def remove_duplicates(self, papers: List[Dict]) -> List[Dict]:
        """
        Remove duplicate articles based on a composite identifier: title and publication year.
        If two articles have the same title and year, compare the abstracts using cosine similarity.
        If the similarity exceeds a threshold, treat them as duplicates.
        """
        unique = []
        for paper in papers:
            title = paper.get("title", "").strip()
            year = paper.get("year", "Unknown")
            composite_id = f"{title} | {year}"
            duplicate_found = False
            for existing in unique:
                existing_title = existing.get("title", "").strip()
                existing_year = existing.get("year", "Unknown")
                existing_id = f"{existing_title} | {existing_year}"
                if composite_id == existing_id:
                    # Check abstract similarity
                    abstract1 = paper.get("abstract", "")
                    abstract2 = existing.get("abstract", "")
                    if abstract1 and abstract2:
                        emb1 = self.model.encode(abstract1, convert_to_tensor=True)
                        emb2 = self.model.encode(abstract2, convert_to_tensor=True)
                        sim = float(util.pytorch_cos_sim(emb1, emb2)[0][0])
                        if sim >= self.similarity_threshold:
                            duplicate_found = True
                            logging.info(f"Removing duplicate (similarity {sim:.2f}): {composite_id}")
                            break
                    else:
                        # If one or both abstracts are missing, consider it a duplicate.
                        duplicate_found = True
                        logging.info(f"Removing duplicate (no abstracts): {composite_id}")
                        break
            if not duplicate_found:
                unique.append(paper)
        return unique

