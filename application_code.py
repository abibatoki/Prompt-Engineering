"""#📌 TIM Pathway Mapper"""

class TIMPathwayMapper:
    PATHWAY_PROFILES = {
        "MDTE": {
            "population": "digital transformation experts, tech leaders",
            "weights": {"semantic": 0.5, "engagement": 0.4, "recency": 0.1},
            "concepts": ["AI adoption", "blockchain", "digital ecosystems", "IoT"],
            "context": "technology-driven organizations, cross-border solutions"
        },
        "MEnt": {
            "population": "entrepreneurs, startup founders, venture capitalists",
            "weights": {"semantic": 0.7, "engagement": 0.2, "recency": 0.1},
            "concepts": ["business scaling", "startup development", "venture funding"],
            "context": "new venture creation, innovative ecosystems"
        },
        "MABA": {
            "population": "business analysts, data scientists, tech professionals",
            "weights": {"semantic": 0.6, "engagement": 0.3, "recency": 0.1},
            "concepts": ["predictive analytics", "big data", "AI-based decision-making"],
            "context": "data-driven business environments"
        },
        "MEng": {
            "population": "engineering researchers, R&D specialists",
            "weights": {"semantic": 0.4, "engagement": 0.4, "recency": 0.2},
            "concepts": ["prototyping", "tech transfer", "product development"],
            "context": "applied engineering, industry-university collaboration"
        }
    }

    def __init__(self):
        self.model = SentenceTransformer('all-mpnet-base-v2')
        self.download_thresholds = {
            "MDTE": 500,  # Base threshold for tech papers
            "MEnt": 300,   # Startups/entrepreneurship papers
            "MABA": 400,   # Business analytics
            "MEng": 250    # Engineering research
        }

    def map_to_pathway(self, pcc_elements: dict) -> str:
        """Enhanced mapping with engagement awareness"""
        best_match = "General"
        max_score = 0

        context_embedding = self.model.encode(pcc_elements["context"], convert_to_tensor=True)
        concept_embedding = self.model.encode(pcc_elements["concept"], convert_to_tensor=True)

        for pathway, profile in self.PATHWAY_PROFILES.items():
            profile_context = self.model.encode(profile["context"], convert_to_tensor=True)
            profile_concept = self.model.encode(" ".join(profile["concepts"]), convert_to_tensor=True)

            # Weighted similarity scoring
            context_sim = util.pytorch_cos_sim(context_embedding, profile_context).item()
            concept_sim = util.pytorch_cos_sim(concept_embedding, profile_concept).item()

            score = (context_sim * profile["weights"]["semantic"] +
                    concept_sim * profile["weights"]["engagement"] +
                    0.1 * profile["weights"]["recency"])

            if score > max_score:
                max_score = score
                best_match = pathway

        return best_match if max_score >= 0.5 else "General"

    def get_engagement_threshold(self, pathway: str) -> int:
        """Returns minimum download threshold for pathway"""
        return self.download_thresholds.get(pathway, 200)

"""#📌 PCC Extractor"""

class PCCExtractor:
    def __init__(self, client: OpenAI):  # Direct OpenAI client injection
        self.nlp = spacy.load("en_core_web_sm")
        self.client = client  # Use client directly

    def extract_pcc_elements(self, query: str) -> Dict[str, str]:
        """Simplified extraction without augmentation"""
        try:
            response = self.client.chat.completions.create(
                model="gpt-4-1106-preview",
                response_format={"type": "json_object"},
                messages=[{
                    "role": "system",
                    "content": "Extract PCC elements as JSON with population, concept, context as lists"
                }, {
                    "role": "user",
                    "content": query
                }]
            )
            pcc_data = json.loads(response.choices[0].message.content)
            return {
                "population": ", ".join(pcc_data.get("population", [])),
                "concept": ", ".join(pcc_data.get("concept", [])),
                "context": ", ".join(pcc_data.get("context", []))
            }
        except Exception as e:
            print(f"GPT extraction failed: {str(e)}")
            return {
                "population": "general population",
                "concept": "general concept",
                "context": "general context"
            }

    def _validate_field(self, value: Any, field_name: str) -> str:
        """Ensure proper formatting of PCC components"""
        if isinstance(value, list):
            return ", ".join([str(item) for item in value])
        if isinstance(value, str):
            return value
        print(f"Invalid format for {field_name}, using default")
        return f"general {field_name}"

"""#📌 Review Question Formulation Module"""

class ReviewQuestionFormulator:
    def __init__(self, framework: str = "PCC"):
        """
        Initialize the formulator with a specific framework.
        Default is PCC (Population, Concept, Context).
        """
        self.framework = framework
        # Initialize the OpenAI client
        self.client = OpenAI()

    def extract_keywords(self, research_objective: str) -> List[str]:
        """Fixed keyword extraction method"""
        prompt = f"""Extract 5-10 keywords from this research objective:
        {research_objective}
        Keywords (comma-separated):"""

        response = self.client.chat.completions.create(
            model="gpt-4-1106-preview",
            messages=[{"role": "user", "content": prompt}],
            temperature=0
        )

        output = response.choices[0].message.content.strip()
        return [kw.strip() for kw in output.split(",") if kw.strip()]

    def generate_review_questions(self, problem_statement: str, num_variations: int = 3) -> List[str]:
        """Fixed generator with strict format enforcement"""
        prompt = f"""You are an expert academic researcher. Given this problem statement:
{problem_statement}

Generate exactly {num_variations} review questions using this EXACT format for each:

[N]. Review Question: [question]
   P: [Population]
   C: [Concept]
   C: [Context]

Rules:
1. Use numbers 1-{num_variations} only
2. Never create sub-bullets or nested lists
3. Maintain 3-space indentation for PCC elements
4. Never combine multiple questions in one list item
5. Strictly follow the line break pattern shown

Example valid output:
1. Review Question: How does X affect Y in Z?
   P: Adult population
   C: Cardiovascular health
   C: Urban environments

Problem Statement: {problem_statement}
Output:"""

        response = self.client.chat.completions.create(
            model="gpt-4-1106-preview",  # More reliable for formatting
            messages=[{"role": "user", "content": prompt}],
            temperature=0
        )

        return self._parse_questions(response.choices[0].message.content)

    def _parse_questions(self, output: str) -> List[str]:
        """Robust parsing of structured output"""
        questions = []
        current_question = []

        for line in output.split('\n'):
            line = line.strip()
            if line.startswith(tuple(f"{i}." for i in range(1, 10))):
                if current_question:
                    questions.append('\n'.join(current_question))
                    current_question = []
                current_question.append(line)
            elif line.startswith(('P:', 'C:')) and current_question:
                current_question.append(line)

        if current_question:
            questions.append('\n'.join(current_question))

        return questions[:3]  # Enforce max 3 questions

    def generate_review_questions_with_pcc(self, problem_statement: str, num_variations: int = 3) -> List[Dict[str, Any]]:
        """Fixed generation with direct PCC extraction"""
        questions = self.generate_review_questions(problem_statement, num_variations)
        pcc_extractor = PCCExtractor(client=self.client)  # Pass formulator's client

        return [{
            "question": q,
            "pcc": pcc_extractor.extract_pcc_elements(q)
        } for q in questions]

